// Writes docs/TEST-WALKTHROUGHS.md from src/lib/testRuns.js (the same test runs the Systems
// Walkthroughs page shows), so the printed sheet and the page never drift.
//   node scripts/test-walkthroughs.mjs
import { writeFileSync } from 'node:fs';
import { TEST_RUNS, WHO } from '../src/lib/testRuns.js';

const SITE = { market: 'p31market.com', collective: 'thep31collective.org', both: 'both sites' };
let out = `# P31 test walkthroughs\n\nStep-by-step test runs for every function on Proverbs 31 Marketplace and The P31 Collective. The same list lives in Systems → Walkthroughs → Test runs, with a checklist. Use TEST in names so test rows are easy to find and remove afterwards. Generated by \`node scripts/test-walkthroughs.mjs\` from \`src/lib/testRuns.js\`.\n\n`;
out += `| # | Test | Who | Where | Minutes |\n|---|------|-----|-------|---------|\n`;
TEST_RUNS.forEach((t, i) => { out += `| ${i + 1} | ${t.title} | ${WHO[t.who]} | ${SITE[t.site]} | ${t.minutes} |\n`; });
out += '\n';
TEST_RUNS.forEach((t, i) => {
  out += `## ${i + 1}. ${t.title}\n\n*${WHO[t.who]} · ${SITE[t.site]} · about ${t.minutes} minutes*\n\n**Do this**\n\n`;
  t.steps.forEach((s, j) => { out += `${j + 1}. ${s}\n`; });
  out += `\n**What should happen**\n\n`;
  t.expect.forEach((e) => { out += `- ${e}\n`; });
  out += `\n**Afterwards:** ${t.cleanup}\n\n`;
});
writeFileSync('docs/TEST-WALKTHROUGHS.md', out);
console.log(`docs/TEST-WALKTHROUGHS.md: ${TEST_RUNS.length} test runs`);
