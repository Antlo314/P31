// The scheduled Auto-create (supabase/functions/studio-autocreate) plans posts with the very same code
// the Studio uses in the browser. Edge Functions can only import from supabase/functions, so this copies
// src/studio/factory/{library,generate}.js into supabase/functions/_shared/factory/.
//   node scripts/sync-factory.mjs          write the copies
//   node scripts/sync-factory.mjs --check  fail if they are out of date (run by `npm run lint`)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'supabase/functions/_shared/factory');
const check = process.argv.includes('--check');
const HEADER = '// GENERATED by scripts/sync-factory.mjs from src/studio/factory. Edit the original, then run the script.\n';

let stale = [];
for (const name of ['library.js', 'generate.js']) {
  // Deno needs the file extension on relative imports.
  const body = readFileSync(join(root, 'src/studio/factory', name), 'utf8').replace(/\r\n/g, '\n').replace(/from '\.\/library'/g, "from './library.js'");
  const want = HEADER + body;
  const target = join(out, name);
  const have = existsSync(target) ? readFileSync(target, 'utf8') : '';
  // Git may check files out with CRLF on Windows; only the content matters.
  const norm = (t) => t.replace(/\r\n/g, '\n');
  if (norm(have) === norm(want)) continue;
  if (check) { stale.push(name); continue; }
  mkdirSync(out, { recursive: true });
  writeFileSync(target, want);
  console.log(`sync-factory: wrote ${name}`);
}
if (stale.length) {
  console.error(`sync-factory: ${stale.join(', ')} out of date. Run: node scripts/sync-factory.mjs`);
  process.exit(1);
}
if (check) console.log('sync-factory: Auto-create copies are current');
