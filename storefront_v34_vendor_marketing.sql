-- ============================================================
-- Storefront v34: vendor marketing
--   1. Products: badge, featured, sale end time
--   2. Shop followers: shoppers leave an email on a storefront; the vendor
--      emails them (one send a day, from the market address, reply-to the vendor)
--   3. Shop campaigns: what each vendor sent and when
-- Run after v33 in the Supabase SQL editor.
-- ============================================================

-- ──────────────────────────────────────────────────────────
-- 1. Product marketing fields
-- ──────────────────────────────────────────────────────────
ALTER TABLE products
ADD COLUMN IF NOT EXISTS badge TEXT,                 -- New, Bestseller, Limited, Handmade, Gift, Back in stock
ADD COLUMN IF NOT EXISTS is_featured BOOLEAN NOT NULL DEFAULT FALSE,
ADD COLUMN IF NOT EXISTS sale_ends_at TIMESTAMPTZ;   -- countdown on the storefront while a sale runs

CREATE INDEX IF NOT EXISTS products_featured_idx ON products (curator_id, is_featured DESC, sort_order);


-- ──────────────────────────────────────────────────────────
-- 2. Shop followers
-- ──────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS shop_subscribers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  curator_id UUID NOT NULL REFERENCES curator_data(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  name TEXT,
  source TEXT DEFAULT 'storefront',           -- storefront, checkout, market
  token UUID NOT NULL DEFAULT gen_random_uuid(),
  unsubscribed BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS shop_subscribers_unique ON shop_subscribers (curator_id, lower(email));
CREATE INDEX IF NOT EXISTS shop_subscribers_token_idx ON shop_subscribers (token);
ALTER TABLE shop_subscribers ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Curators read own followers" ON shop_subscribers;
CREATE POLICY "Curators read own followers" ON shop_subscribers
FOR SELECT TO authenticated
USING (curator_id = auth.uid() OR public.is_admin());

DROP POLICY IF EXISTS "Curators remove own followers" ON shop_subscribers;
CREATE POLICY "Curators remove own followers" ON shop_subscribers
FOR DELETE TO authenticated
USING (curator_id = auth.uid() OR public.is_admin());

-- Shoppers follow a shop from its storefront (no account). Rate limited; re-following clears an unsubscribe.
CREATE OR REPLACE FUNCTION public.shop_subscribe(p_curator UUID, p_email TEXT, p_name TEXT DEFAULT NULL, p_source TEXT DEFAULT 'storefront')
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_email TEXT := lower(trim(p_email));
BEGIN
  IF v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' THEN
    RAISE EXCEPTION 'Enter a valid email address';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM curator_data WHERE id = p_curator AND status = 'approved') THEN
    RAISE EXCEPTION 'Shop not found';
  END IF;
  IF (SELECT count(*) FROM shop_subscribers WHERE created_at > NOW() - interval '1 minute') > 60 THEN
    RAISE EXCEPTION 'Too many sign-ups right now, please try again in a minute';
  END IF;
  INSERT INTO shop_subscribers (curator_id, email, name, source)
  VALUES (p_curator, v_email, NULLIF(trim(p_name), ''), COALESCE(NULLIF(p_source, ''), 'storefront'))
  ON CONFLICT (curator_id, lower(email)) DO UPDATE
    SET unsubscribed = FALSE, name = COALESCE(EXCLUDED.name, shop_subscribers.name);
  RETURN TRUE;
END;
$$;
GRANT EXECUTE ON FUNCTION public.shop_subscribe(UUID, TEXT, TEXT, TEXT) TO anon, authenticated;

-- One-click unsubscribe from a shop (link in every shop email).
CREATE OR REPLACE FUNCTION public.shop_unsubscribe(p_token UUID)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  UPDATE shop_subscribers SET unsubscribed = TRUE WHERE token = p_token RETURNING TRUE;
$$;
GRANT EXECUTE ON FUNCTION public.shop_unsubscribe(UUID) TO anon, authenticated;

-- Follower count shown on the storefront (number only, no emails).
CREATE OR REPLACE FUNCTION public.shop_follower_count(p_curator UUID)
RETURNS INTEGER
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
  SELECT count(*)::INTEGER FROM shop_subscribers WHERE curator_id = p_curator AND NOT unsubscribed;
$$;
GRANT EXECUTE ON FUNCTION public.shop_follower_count(UUID) TO anon, authenticated;


-- ──────────────────────────────────────────────────────────
-- 3. Shop campaigns (sent by the shop-broadcast function)
-- ──────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS shop_campaigns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  curator_id UUID NOT NULL REFERENCES curator_data(id) ON DELETE CASCADE DEFAULT auth.uid(),
  subject TEXT NOT NULL,
  body TEXT NOT NULL,
  product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'sending', 'sent', 'failed')),
  sent_count INTEGER NOT NULL DEFAULT 0,
  error TEXT,
  sent_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS shop_campaigns_curator_idx ON shop_campaigns (curator_id, created_at DESC);
ALTER TABLE shop_campaigns ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Curators manage own campaigns" ON shop_campaigns;
CREATE POLICY "Curators manage own campaigns" ON shop_campaigns
FOR ALL TO authenticated
USING (curator_id = auth.uid() OR public.is_admin())
WITH CHECK (curator_id = auth.uid() OR public.is_admin());

-- Only the sender function records sends.
CREATE OR REPLACE FUNCTION public.guard_shop_campaign_sends()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.is_trusted_writer() THEN
    NEW.status := CASE WHEN TG_OP = 'INSERT' THEN 'draft' WHEN OLD.status = 'draft' THEN 'draft' ELSE OLD.status END;
    NEW.sent_count := CASE WHEN TG_OP = 'INSERT' THEN 0 ELSE OLD.sent_count END;
    NEW.sent_at := CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE OLD.sent_at END;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS guard_shop_campaign_sends ON shop_campaigns;
CREATE TRIGGER guard_shop_campaign_sends BEFORE INSERT OR UPDATE ON shop_campaigns
FOR EACH ROW EXECUTE FUNCTION public.guard_shop_campaign_sends();

-- Product-level numbers for the vendor (opens, buys, shares per product, last 30 days).
CREATE OR REPLACE FUNCTION public.my_product_stats(p_days INTEGER DEFAULT 30)
RETURNS TABLE (product_id BIGINT, opens BIGINT, buys BIGINT, shares BIGINT)
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
  SELECT a.product_id,
         count(*) FILTER (WHERE a.event_type = 'product_click') AS opens,
         count(*) FILTER (WHERE a.event_type = 'payment_click') AS buys,
         count(*) FILTER (WHERE a.event_type = 'share') AS shares
  FROM curator_analytics a
  WHERE a.curator_id = auth.uid()
    AND a.product_id IS NOT NULL
    AND a.created_at > NOW() - make_interval(days => GREATEST(COALESCE(p_days, 30), 1))
  GROUP BY a.product_id
  ORDER BY opens DESC;
$$;
GRANT EXECUTE ON FUNCTION public.my_product_stats(INTEGER) TO authenticated;
