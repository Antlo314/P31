/* ============================================================
   P31 - v45: the watchdog
   Run after v44. Safe to run more than once.

   HOW TO RUN (no pasting): from the project folder
     npx supabase db query --linked --project-ref xsnhxjttdizljaawpumz -f storefront_v45_watchdog.sql
   The result is one row: alerts_ready true, runs_ready true,
   cron_health_ready true, watchdog_scheduled true.

   Every hour the watchdog function checks the whole system and fixes
   what it safely can on its own:
     - Instagram and Facebook: connected, and login tokens not about
       to expire
     - posts that failed (each is retried once automatically)
     - how many days ahead posts are booked
     - form emails that did not go out (it runs the sender again)
     - applications and requests waiting more than two days
     - site errors, scheduled jobs that failed or stopped, database
       updates waiting, email not configured
   Problems are kept here as alerts (open until the check passes
   again), shown in Systems > Health and on Today, and emailed: right
   away when something breaks, and once a morning while anything is
   still open.

   1. ops_alerts: one row per open problem (a key per problem, so it
      is never alerted twice), with how to fix it.
   2. ops_runs: a short record of each run (kept 30 days).
   3. ops_cron_health(): the scheduled jobs, when each last ran and
      whether it failed (for the watchdog only).
   4. The hourly schedule (at 7 minutes past).
   ============================================================ */

-- ----------------------------------------------------------
-- 1. Alerts
-- ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ops_alerts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  key TEXT NOT NULL,
  severity TEXT NOT NULL DEFAULT 'warn' CHECK (severity IN ('warn', 'fail')),
  area TEXT NOT NULL DEFAULT 'system',
  title TEXT NOT NULL,
  detail TEXT,
  fix TEXT,
  link TEXT,
  meta JSONB NOT NULL DEFAULT '{}'::jsonb,
  first_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
  notified_at TIMESTAMPTZ,
  snoozed_until TIMESTAMPTZ,
  resolved_at TIMESTAMPTZ,
  resolved_by TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ops_alerts_open_key ON public.ops_alerts (key) WHERE resolved_at IS NULL;
CREATE INDEX IF NOT EXISTS ops_alerts_recent ON public.ops_alerts (last_seen DESC);
ALTER TABLE public.ops_alerts ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admins read alerts" ON public.ops_alerts;
CREATE POLICY "Admins read alerts" ON public.ops_alerts
  FOR SELECT TO authenticated
  USING (public.is_academy_admin() OR public.is_operator());
-- Admins can snooze an alert or mark it handled; the watchdog reopens it if the check still fails.
DROP POLICY IF EXISTS "Admins handle alerts" ON public.ops_alerts;
CREATE POLICY "Admins handle alerts" ON public.ops_alerts
  FOR UPDATE TO authenticated
  USING (public.is_academy_admin() OR public.is_operator())
  WITH CHECK (public.is_academy_admin() OR public.is_operator());
GRANT SELECT, UPDATE ON public.ops_alerts TO authenticated;

-- ----------------------------------------------------------
-- 2. Runs
-- ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ops_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ran_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  source TEXT NOT NULL DEFAULT 'cron',
  ok BOOLEAN NOT NULL DEFAULT true,
  open_alerts INTEGER NOT NULL DEFAULT 0,
  checks JSONB NOT NULL DEFAULT '[]'::jsonb,
  healed JSONB NOT NULL DEFAULT '[]'::jsonb,
  emailed TEXT,
  took_ms INTEGER
);
CREATE INDEX IF NOT EXISTS ops_runs_recent ON public.ops_runs (ran_at DESC);
ALTER TABLE public.ops_runs ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admins read runs" ON public.ops_runs;
CREATE POLICY "Admins read runs" ON public.ops_runs
  FOR SELECT TO authenticated
  USING (public.is_academy_admin() OR public.is_operator());
GRANT SELECT ON public.ops_runs TO authenticated;

-- ----------------------------------------------------------
-- 3. Scheduled jobs, as the watchdog sees them
-- ----------------------------------------------------------
CREATE OR REPLACE FUNCTION public.ops_cron_health()
RETURNS TABLE (jobname TEXT, schedule TEXT, active BOOLEAN, last_start TIMESTAMPTZ, last_status TEXT, last_message TEXT, runs_24h INTEGER, failed_24h INTEGER)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public
AS $fn$
BEGIN
  IF to_regclass('cron.job') IS NULL OR to_regclass('cron.job_run_details') IS NULL THEN
    RETURN;
  END IF;
  RETURN QUERY EXECUTE $q$
    SELECT j.jobname::text, j.schedule::text, j.active,
           d.start_time, d.status::text, left(d.return_message, 300)::text,
           (SELECT count(*)::int FROM cron.job_run_details r WHERE r.jobid = j.jobid AND r.start_time > now() - interval '24 hours'),
           (SELECT count(*)::int FROM cron.job_run_details r WHERE r.jobid = j.jobid AND r.start_time > now() - interval '24 hours' AND r.status = 'failed')
      FROM cron.job j
      LEFT JOIN LATERAL (
        SELECT r.start_time, r.status, r.return_message FROM cron.job_run_details r
         WHERE r.jobid = j.jobid ORDER BY r.start_time DESC LIMIT 1
      ) d ON true
     WHERE j.jobname LIKE 'p31-%'
     ORDER BY j.jobname
  $q$;
END;
$fn$;
REVOKE ALL ON FUNCTION public.ops_cron_health() FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.ops_cron_health() TO service_role;

-- ----------------------------------------------------------
-- 4. The hourly schedule
-- ----------------------------------------------------------
DO $jobs$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    CREATE EXTENSION pg_cron WITH SCHEMA pg_catalog;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_net') THEN
    CREATE EXTENSION pg_net WITH SCHEMA extensions;
  END IF;
END;
$jobs$;

SELECT cron.unschedule(jobid) FROM cron.job WHERE jobname = 'p31-watchdog';

-- Every hour at :07: check everything, fix what is safe to fix, alert on the rest.
SELECT cron.schedule('p31-watchdog', '7 * * * *', $job$
  SELECT net.http_post(
    url := 'https://xsnhxjttdizljaawpumz.supabase.co/functions/v1/watchdog',
    headers := '{"Content-Type": "application/json"}'::jsonb,
    body := '{"source": "cron"}'::jsonb,
    timeout_milliseconds := 120000);
$job$);

-- ----------------------------------------------------------
-- 5. Record this script, then one row to prove it
-- ----------------------------------------------------------
DO $ver$
BEGIN
  IF to_regclass('public.schema_versions') IS NOT NULL THEN
    INSERT INTO public.schema_versions (version, name) VALUES (45, 'watchdog') ON CONFLICT (version) DO NOTHING;
  END IF;
END;
$ver$;

SELECT
  to_regclass('public.ops_alerts') IS NOT NULL AS alerts_ready,
  to_regclass('public.ops_runs') IS NOT NULL AS runs_ready,
  EXISTS (SELECT 1 FROM pg_proc WHERE proname = 'ops_cron_health') AS cron_health_ready,
  EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'p31-watchdog') AS watchdog_scheduled;
