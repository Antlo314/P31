-- One trigger for every table: argument 1 lists the fields worth logging on an update (empty: all),
-- argument 2 names the owner column (a person changing her own row is not logged).
-- Writes by the system (no signed-in person) are not logged here.
CREATE OR REPLACE FUNCTION public.log_admin_activity()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth
AS $fn$
DECLARE
  v_new JSONB := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END;
  v_old JSONB := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END;
  v_row JSONB;
  v_keys TEXT[];
  v_owner TEXT;
  v_changes JSONB := '{}'::jsonb;
  k TEXT;
  v_actor UUID := auth.uid();
  v_email TEXT;
  v_name TEXT;
BEGIN
  IF v_actor IS NULL THEN RETURN NULL; END IF;
  v_row := coalesce(v_new, v_old);
  v_keys := CASE WHEN TG_NARGS > 0 AND TG_ARGV[0] <> '' THEN string_to_array(TG_ARGV[0], ',') END;
  v_owner := CASE WHEN TG_NARGS > 1 AND TG_ARGV[1] <> '' THEN TG_ARGV[1] END;
  IF v_owner IS NOT NULL AND v_row->>v_owner = v_actor::text THEN RETURN NULL; END IF;
  IF TG_OP = 'UPDATE' THEN
    FOR k IN SELECT jsonb_object_keys(v_new) LOOP
      IF (v_keys IS NULL OR k = ANY (v_keys)) AND k NOT IN ('updated_at', 'created_at', 'last_message_at')
         AND (v_new->k) IS DISTINCT FROM (v_old->k) THEN
        v_changes := v_changes || jsonb_build_object(k, jsonb_build_array(v_old->k, v_new->k));
      END IF;
    END LOOP;
    IF v_changes = '{}'::jsonb THEN RETURN NULL; END IF;
  END IF;
  SELECT lower(u.email), coalesce(nullif(btrim(p.full_name), ''), u.raw_user_meta_data->>'full_name')
    INTO v_email, v_name
    FROM auth.users u LEFT JOIN profiles p ON p.id = u.id WHERE u.id = v_actor;
  INSERT INTO admin_activity (actor_id, actor_email, actor_name, area, action, target_id, target_label, changes)
  VALUES (v_actor, v_email, v_name, TG_TABLE_NAME, lower(TG_OP),
          coalesce(v_row->>'id', v_row->>'email', v_row->>'key'),
          left(coalesce(v_row->>'business_name', v_row->>'title', v_row->>'subject', v_row->>'full_name',
                        v_row->>'display_name', v_row->>'name', v_row->>'label', v_row->>'email', v_row->>'key'), 200),
          v_changes);
  RETURN NULL;
END;
$fn$;

