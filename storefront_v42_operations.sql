-- The shop guard, as in v18, now also protecting the billing fields from the vendor herself.
CREATE OR REPLACE FUNCTION public.guard_curator_data()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $fn$
DECLARE
  protected TEXT[] := ARRAY[
    'is_paid', 'is_published', 'is_featured', 'is_early_bird',
    'verification_badges', 'admin_feedback', 'branding_package_unlocked',
    'stripe_account_id', 'stripe_charges_enabled',
    'stripe_payouts_enabled', 'stripe_details_submitted', 'plan',
    'activated_at', 'trial_ends_at', 'subscription_status', 'stripe_billing_customer_id',
    'stripe_subscription_id', 'subscription_current_end', 'billing_notice', 'billing_notice_at'
  ];
  new_j JSONB;
  old_j JSONB;
  k TEXT;
  pre_approved BOOLEAN;
BEGIN
  IF public.is_trusted_writer() THEN
    RETURN NEW;
  END IF;

  new_j := to_jsonb(NEW);

  IF TG_OP = 'INSERT' THEN
    SELECT EXISTS (
      SELECT 1 FROM vendor_approvals va
      JOIN auth.users u ON lower(u.email) = lower(va.email)
      WHERE u.id = auth.uid()
    ) INTO pre_approved;

    new_j := new_j
      || jsonb_build_object(
           'status',       CASE WHEN pre_approved THEN 'approved' ELSE 'pending' END,
           'is_paid',      pre_approved,
           'is_published', pre_approved);
    IF new_j ? 'is_featured'               THEN new_j := new_j || '{"is_featured": false}'; END IF;
    IF new_j ? 'verification_badges'       THEN new_j := new_j || '{"verification_badges": null}'; END IF;
    IF new_j ? 'admin_feedback'            THEN new_j := new_j || '{"admin_feedback": null}'; END IF;
    IF new_j ? 'branding_package_unlocked' THEN new_j := new_j || '{"branding_package_unlocked": false}'; END IF;
    IF new_j ? 'stripe_account_id'         THEN new_j := new_j || '{"stripe_account_id": null}'; END IF;
    IF new_j ? 'stripe_charges_enabled'    THEN new_j := new_j || '{"stripe_charges_enabled": false}'; END IF;
    IF new_j ? 'stripe_payouts_enabled'    THEN new_j := new_j || '{"stripe_payouts_enabled": false}'; END IF;
    IF new_j ? 'stripe_details_submitted'  THEN new_j := new_j || '{"stripe_details_submitted": false}'; END IF;
    IF new_j ? 'plan'                      THEN new_j := new_j || '{"plan": "free"}'; END IF;
    new_j := new_j || '{"activated_at": null, "trial_ends_at": null, "subscription_status": "none", "stripe_billing_customer_id": null, "stripe_subscription_id": null, "subscription_current_end": null, "billing_notice": null, "billing_notice_at": null}';

  ELSE -- UPDATE
    old_j := to_jsonb(OLD);
    FOREACH k IN ARRAY protected LOOP
      IF old_j ? k THEN
        new_j := jsonb_set(new_j, ARRAY[k], old_j -> k);
      END IF;
    END LOOP;

    IF NOT (
      NEW.status IS NOT DISTINCT FROM OLD.status
      OR (NEW.status = 'pending' AND coalesce(OLD.status, 'draft') IN ('draft', 'rejected'))
    ) THEN
      new_j := jsonb_set(new_j, '{status}', to_jsonb(OLD.status));
    END IF;
  END IF;

  NEW := jsonb_populate_record(NEW, new_j);
  RETURN NEW;
END;
$fn$;

-- A shop approved from now on starts its free period (early-bird shops are complimentary).
-- Runs after the guard (triggers fire in name order), so it sees the final status.
CREATE OR REPLACE FUNCTION public.storefront_start_free_period()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $fn$
DECLARE v_months INTEGER;
BEGIN
  IF NEW.status = 'approved' AND NEW.activated_at IS NULL AND NEW.subscription_status = 'none'
     AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM 'approved') THEN
    SELECT coalesce((value->>'free_months')::int, 3) INTO v_months FROM app_settings WHERE key = 'billing';
    NEW.activated_at := now();
    IF coalesce(NEW.is_early_bird, false) THEN
      NEW.subscription_status := 'comp';
    ELSE
      NEW.subscription_status := 'trial';
      NEW.trial_ends_at := now() + make_interval(months => coalesce(v_months, 3));
    END IF;
  END IF;
  RETURN NEW;
END;
$fn$;
DROP TRIGGER IF EXISTS storefront_start_free_period ON public.curator_data;
CREATE TRIGGER storefront_start_free_period BEFORE INSERT OR UPDATE OF status ON public.curator_data
  FOR EACH ROW EXECUTE FUNCTION public.storefront_start_free_period();

-- Systems -> Curators and shops: billing actions for one shop, or start the free period for every
-- approved shop that has none yet.
--   start      free period from today (or p_days days if given)
--   extend     add p_days to the free period
--   comp       complimentary storefront (no subscription)
--   none       take the shop out of billing
CREATE OR REPLACE FUNCTION public.storefront_billing_admin(p_id UUID, p_action TEXT, p_days INTEGER DEFAULT NULL)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $fn$
DECLARE v_months INTEGER; v_count INTEGER := 0;
BEGIN
  IF NOT public.can_run_shops() THEN RAISE EXCEPTION 'Only admins and the shops dashboard can change billing.'; END IF;
  SELECT coalesce((value->>'free_months')::int, 3) INTO v_months FROM app_settings WHERE key = 'billing';
  PERFORM set_config('p31.trusted', 'on', true);
  IF p_action = 'start_all' THEN
    UPDATE curator_data SET activated_at = coalesce(activated_at, now()), subscription_status = 'trial',
           trial_ends_at = now() + make_interval(months => coalesce(v_months, 3)), billing_notice = NULL, billing_notice_at = NULL
     WHERE status = 'approved' AND subscription_status = 'none' AND NOT coalesce(is_early_bird, false);
    GET DIAGNOSTICS v_count = ROW_COUNT;
  ELSIF p_action = 'start' THEN
    UPDATE curator_data SET activated_at = coalesce(activated_at, now()), subscription_status = 'trial',
           trial_ends_at = CASE WHEN p_days IS NULL THEN now() + make_interval(months => coalesce(v_months, 3)) ELSE now() + make_interval(days => p_days) END,
           billing_notice = NULL, billing_notice_at = NULL
     WHERE id = p_id;
    GET DIAGNOSTICS v_count = ROW_COUNT;
  ELSIF p_action = 'extend' THEN
    UPDATE curator_data SET subscription_status = CASE WHEN subscription_status IN ('ended', 'none') THEN 'trial' ELSE subscription_status END,
           trial_ends_at = greatest(coalesce(trial_ends_at, now()), now()) + make_interval(days => coalesce(p_days, 30)),
           billing_notice = NULL, billing_notice_at = NULL
     WHERE id = p_id;
    GET DIAGNOSTICS v_count = ROW_COUNT;
  ELSIF p_action IN ('comp', 'none') THEN
    UPDATE curator_data SET subscription_status = p_action, billing_notice = NULL, billing_notice_at = NULL WHERE id = p_id;
    GET DIAGNOSTICS v_count = ROW_COUNT;
  ELSE
    PERFORM set_config('p31.trusted', '', true);
    RAISE EXCEPTION 'Unknown billing action.';
  END IF;
  PERFORM set_config('p31.trusted', '', true);
  RETURN jsonb_build_object('changed', v_count);
END;
$fn$;
REVOKE ALL ON FUNCTION public.storefront_billing_admin(UUID, TEXT, INTEGER) FROM public, anon;
GRANT EXECUTE ON FUNCTION public.storefront_billing_admin(UUID, TEXT, INTEGER) TO authenticated;

